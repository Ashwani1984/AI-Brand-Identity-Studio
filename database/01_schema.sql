-- AI Brand Identity Studio — SQL Server schema (Phase 1)
-- Database: AiBrandStudio

IF DB_ID(N'AiBrandStudio') IS NULL
    CREATE DATABASE AiBrandStudio;
GO

USE AiBrandStudio;
GO

CREATE TABLE Roles (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    Name NVARCHAR(64) NOT NULL UNIQUE,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Users (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    Email NVARCHAR(256) NOT NULL UNIQUE,
    PasswordHash NVARCHAR(512) NOT NULL,
    FullName NVARCHAR(200) NOT NULL,
    CreditBalance INT NOT NULL DEFAULT 0,
    IsActive BIT NOT NULL DEFAULT 1,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAtUtc DATETIME2 NULL
);

CREATE TABLE UserRoles (
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    RoleId UNIQUEIDENTIFIER NOT NULL REFERENCES Roles(Id),
    PRIMARY KEY (UserId, RoleId)
);

CREATE TABLE RefreshTokens (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    TokenHash NVARCHAR(128) NOT NULL,
    ExpiresAtUtc DATETIME2 NOT NULL,
    RevokedAtUtc DATETIME2 NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE OAuthAccounts (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    Provider NVARCHAR(32) NOT NULL,
    ProviderUserId NVARCHAR(256) NOT NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    CONSTRAINT UQ_OAuth UNIQUE (Provider, ProviderUserId)
);

CREATE TABLE SubscriptionPlans (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    Code NVARCHAR(64) NOT NULL UNIQUE,
    Name NVARCHAR(128) NOT NULL,
    MonthlyPriceInr DECIMAL(18,2) NOT NULL,
    MonthlyCredits INT NOT NULL,
    IsActive BIT NOT NULL DEFAULT 1
);

CREATE TABLE Subscriptions (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    PlanId UNIQUEIDENTIFIER NOT NULL REFERENCES SubscriptionPlans(Id),
    Status NVARCHAR(32) NOT NULL,
    CurrentPeriodEndUtc DATETIME2 NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Payments (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    Provider NVARCHAR(32) NOT NULL,
    ProviderOrderId NVARCHAR(128) NULL,
    Amount DECIMAL(18,2) NOT NULL,
    Currency NVARCHAR(8) NOT NULL DEFAULT 'INR',
    Status NVARCHAR(32) NOT NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE CreditLedgers (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    Delta INT NOT NULL,
    Reason NVARCHAR(128) NOT NULL,
    ReferenceId UNIQUEIDENTIFIER NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Projects (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    Name NVARCHAR(200) NOT NULL,
    Status NVARCHAR(32) NOT NULL DEFAULT 'Draft',
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAtUtc DATETIME2 NULL
);

CREATE TABLE Brands (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    ProjectId UNIQUEIDENTIFIER NOT NULL REFERENCES Projects(Id),
    BusinessName NVARCHAR(200) NOT NULL,
    Industry NVARCHAR(128) NULL,
    Audience NVARCHAR(512) NULL,
    Competitors NVARCHAR(512) NULL,
    Country NVARCHAR(64) NULL,
    Language NVARCHAR(64) NULL,
    Style NVARCHAR(128) NULL,
    Mood NVARCHAR(128) NULL,
    PreferredColors NVARCHAR(256) NULL,
    PreferredFonts NVARCHAR(256) NULL,
    Keywords NVARCHAR(512) NULL,
    Mission NVARCHAR(MAX) NULL,
    Vision NVARCHAR(MAX) NULL,
    Usp NVARCHAR(MAX) NULL,
    GeneratedName NVARCHAR(200) NULL,
    Tagline NVARCHAR(300) NULL,
    BrandStory NVARCHAR(MAX) NULL,
    BrandVoice NVARCHAR(MAX) NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
    UpdatedAtUtc DATETIME2 NULL
);

CREATE TABLE BrandVersions (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    BrandId UNIQUEIDENTIFIER NOT NULL REFERENCES Brands(Id),
    VersionNumber INT NOT NULL,
    SnapshotJson NVARCHAR(MAX) NOT NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Prompts (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    BrandId UNIQUEIDENTIFIER NULL REFERENCES Brands(Id),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    Provider NVARCHAR(64) NOT NULL,
    Kind NVARCHAR(64) NOT NULL,
    InputText NVARCHAR(MAX) NOT NULL,
    OutputText NVARCHAR(MAX) NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Logos (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    BrandId UNIQUEIDENTIFIER NOT NULL REFERENCES Brands(Id),
    Style NVARCHAR(64) NOT NULL,
    PromptText NVARCHAR(MAX) NOT NULL,
    ImageUrl NVARCHAR(1024) NULL,
    SvgContent NVARCHAR(MAX) NULL,
    Provider NVARCHAR(64) NOT NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Palettes (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    BrandId UNIQUEIDENTIFIER NOT NULL REFERENCES Brands(Id),
    PrimaryHex NVARCHAR(16) NOT NULL,
    SecondaryHex NVARCHAR(16) NOT NULL,
    AccentHex NVARCHAR(16) NOT NULL,
    BackgroundHex NVARCHAR(16) NOT NULL,
    TypographyHex NVARCHAR(16) NOT NULL,
    CssExport NVARCHAR(MAX) NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Fonts (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    BrandId UNIQUEIDENTIFIER NOT NULL REFERENCES Brands(Id),
    HeadlineFont NVARCHAR(128) NOT NULL,
    BodyFont NVARCHAR(128) NOT NULL,
    MonoFont NVARCHAR(128) NULL,
    GoogleFontsUrl NVARCHAR(512) NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Assets (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    ProjectId UNIQUEIDENTIFIER NULL REFERENCES Projects(Id),
    BrandId UNIQUEIDENTIFIER NULL REFERENCES Brands(Id),
    Kind NVARCHAR(64) NOT NULL,
    FileName NVARCHAR(256) NOT NULL,
    ContentType NVARCHAR(128) NOT NULL,
    StoragePath NVARCHAR(1024) NOT NULL,
    ByteSize BIGINT NOT NULL DEFAULT 0,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Mockups (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    BrandId UNIQUEIDENTIFIER NOT NULL REFERENCES Brands(Id),
    MockupType NVARCHAR(64) NOT NULL,
    ImageUrl NVARCHAR(1024) NULL,
    PromptText NVARCHAR(MAX) NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Videos (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    BrandId UNIQUEIDENTIFIER NOT NULL REFERENCES Brands(Id),
    Provider NVARCHAR(64) NOT NULL,
    PromptText NVARCHAR(MAX) NOT NULL,
    StoryboardJson NVARCHAR(MAX) NULL,
    Status NVARCHAR(32) NOT NULL DEFAULT 'Draft',
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Exports (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    ProjectId UNIQUEIDENTIFIER NOT NULL REFERENCES Projects(Id),
    Format NVARCHAR(32) NOT NULL,
    StoragePath NVARCHAR(1024) NOT NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Notifications (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    UserId UNIQUEIDENTIFIER NOT NULL REFERENCES Users(Id),
    Title NVARCHAR(200) NOT NULL,
    Body NVARCHAR(1000) NOT NULL,
    IsRead BIT NOT NULL DEFAULT 0,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE AuditLogs (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    UserId UNIQUEIDENTIFIER NULL,
    Action NVARCHAR(128) NOT NULL,
    EntityType NVARCHAR(128) NULL,
    EntityId UNIQUEIDENTIFIER NULL,
    IpAddress NVARCHAR(64) NULL,
    MetadataJson NVARCHAR(MAX) NULL,
    CreatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE AiProviderConfigs (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    ProviderName NVARCHAR(64) NOT NULL UNIQUE,
    IsEnabled BIT NOT NULL DEFAULT 0,
    ApiKeyMasked NVARCHAR(128) NULL,
    UpdatedAtUtc DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME()
);

CREATE TABLE Templates (
    Id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY DEFAULT NEWSEQUENTIALID(),
    Code NVARCHAR(64) NOT NULL UNIQUE,
    Name NVARCHAR(128) NOT NULL,
    Category NVARCHAR(64) NOT NULL,
    ContentJson NVARCHAR(MAX) NOT NULL,
    IsActive BIT NOT NULL DEFAULT 1
);

CREATE INDEX IX_Projects_UserId ON Projects(UserId);
CREATE INDEX IX_Brands_ProjectId ON Brands(ProjectId);
CREATE INDEX IX_Assets_UserId ON Assets(UserId);
CREATE INDEX IX_CreditLedgers_UserId ON CreditLedgers(UserId);
CREATE INDEX IX_AuditLogs_CreatedAtUtc ON AuditLogs(CreatedAtUtc);
GO
